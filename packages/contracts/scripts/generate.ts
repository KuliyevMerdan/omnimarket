/**
 * Turns forge artifacts into `as const` TypeScript so viem infers function names, args and
 * event types end to end. Run after `forge build` (see `pnpm build`).
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const contracts = { OmniMarket: 'omniMarket', OmniNFT: 'omniNft' } as const
const outDir = join(root, 'ts', 'generated')
mkdirSync(outDir, { recursive: true })

const header = '// Generated by scripts/generate.ts from forge artifacts. Do not edit.\n'
let abis = header
let bytecode = header

for (const [name, camel] of Object.entries(contracts)) {
  const artifact = JSON.parse(readFileSync(join(root, 'out', `${name}.sol`, `${name}.json`), 'utf8')) as {
    abi: unknown[]
    bytecode: { object: string }
  }
  abis += `\nexport const ${camel}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const\n`
  bytecode += `\nexport const ${camel}Bytecode = '${artifact.bytecode.object}' as const\n`
}

writeFileSync(join(outDir, 'abis.ts'), abis)
writeFileSync(join(outDir, 'bytecode.ts'), bytecode)
console.log(`generated ${Object.keys(contracts).join(', ')} → ts/generated`)
